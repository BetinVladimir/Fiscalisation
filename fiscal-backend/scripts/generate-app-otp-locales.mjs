import { writeFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';

const languages = {
  bg: 'Bulgarian', hr: 'Croatian', cs: 'Czech', da: 'Danish', nl: 'Dutch',
  en: 'English', et: 'Estonian', fi: 'Finnish', fr: 'French', de: 'German',
  el: 'Greek', hu: 'Hungarian', ga: 'Irish', it: 'Italian', lv: 'Latvian',
  lt: 'Lithuanian', mt: 'Maltese', pl: 'Polish', pt: 'Portuguese', ro: 'Romanian',
  sk: 'Slovak', sl: 'Slovenian', es: 'Spanish', sv: 'Swedish', ru: 'Russian',
};
const copy = {
  bg: { subject: 'Код за вход в BeeFiscal', prefix: 'Вашият код за вход в BeeFiscal е: ' },
  en: { subject: 'BeeFiscal sign-in code', prefix: 'Your BeeFiscal sign-in code is: ' },
  et: { subject: 'BeeFiscali sisselogimiskood', prefix: 'Teie BeeFiscali sisselogimiskood on: ' },
  ga: { subject: 'Cód logála isteach BeeFiscal', prefix: 'Is é do chód logála isteach BeeFiscal: ' },
  lv: { subject: 'BeeFiscal pierakstīšanās kods', prefix: 'Jūsu BeeFiscal pierakstīšanās kods ir: ' },
  ru: { subject: 'Код входа в BeeFiscal', prefix: 'Ваш код входа в BeeFiscal: ' },
  sl: { subject: 'Koda za prijavo v BeeFiscal', prefix: 'Vaša koda za prijavo v BeeFiscal je: ' },
};

for (const [code, name] of Object.entries(languages)) {
  if (copy[code]) continue;
  const prompt = `Translate these two short authentication email strings into ${name} (${code}). Return JSON with exactly subject and prefix string fields. Preserve the product name BeeFiscal verbatim. Do not include any digits or sample code. The prefix must end with a colon and one space so a six-digit code can be appended. Source subject: "BeeFiscal sign-in code". Source prefix: "Your BeeFiscal sign-in code is: ". Translate naturally for a professional transactional email.`;
  const response = await fetch('http://127.0.0.1:11434/api/generate', {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ model: 'qwen3.5:9b-mlx', prompt, stream: false, think: false, format: 'json', options: { temperature: 0 } }),
  });
  if (!response.ok) throw new Error(`${code}: Ollama HTTP ${response.status}`);
  const generated = JSON.parse((await response.json()).response);
  if (typeof generated.subject !== 'string' || typeof generated.prefix !== 'string' ||
      !generated.prefix.includes('BeeFiscal') ||
      !generated.subject.trim() || !generated.prefix.trim() || /\d/.test(generated.subject + generated.prefix)) {
    throw new Error(`${code}: invalid translation ${JSON.stringify(generated)}`);
  }
  const subject = generated.subject.includes('BeeFiscal') ? generated.subject.trim() : `${generated.subject.trim()} — BeeFiscal`;
  copy[code] = { subject, prefix: `${generated.prefix.trimEnd()} ` };
  process.stdout.write(`${code} `);
}

const quote = value => JSON.stringify(value);
const rows = Object.entries(languages).map(([code]) => {
  const item = copy[code];
  return `\t${quote(code)}: {subject: ${quote(item.subject)}, prefix: ${quote(item.prefix)}},`;
});
const source = `// Code generated by scripts/generate-app-otp-locales.mjs using local Ollama qwen3.5:9b-mlx; DO NOT EDIT.\n// Human editorial review of generated translations is still required.\npackage integration\n\ntype appOTPCopy struct { subject, prefix string }\n\nvar appOTPCopies = map[string]appOTPCopy{\n${rows.join('\n')}\n}\n`;
const output = new URL('../internal/integration/otp_locale.generated.go', import.meta.url);
await writeFile(output, source);
execFileSync('gofmt', ['-w', output.pathname]);
process.stdout.write('\n');
